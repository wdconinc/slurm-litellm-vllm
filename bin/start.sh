#!/bin/bash

# Default model key
MODEL_KEY=${1:-mistral}

echo "Submitting vLLM Slurm job for model: $MODEL_KEY..."

# Submit the job
OUTPUT=$(sbatch bin/vllm.sh "$MODEL_KEY" 2>&1)
if [ $? -ne 0 ]; then
    echo "Error: Failed to submit Slurm job."
    echo "$OUTPUT"
    exit 1
fi

echo "$OUTPUT"
# Extract job ID assuming output format like "Submitted batch job 123456"
JOB_ID=$(echo "$OUTPUT" | awk '{print $4}')

if [[ -z "$JOB_ID" || ! "$JOB_ID" =~ ^[0-9]+$ ]]; then
    echo "Warning: Could not parse job ID from sbatch output. Will wait for config file indefinitely."
else
    echo "Waiting for Slurm job $JOB_ID to initialize and generate LiteLLM config..."
    echo "(This may take a few minutes while the container starts and the model loads)"
fi

# Wait until the endpoint file is generated by the compute node
ENDPOINT_FILE="$HOME/litellm/etc/endpoint.env"
rm -f "$ENDPOINT_FILE"

# Wait until the config file is generated
while [ ! -f "$ENDPOINT_FILE" ]; do
    if [[ -n "$JOB_ID" && "$JOB_ID" =~ ^[0-9]+$ ]]; then
        if ! squeue -h -j "$JOB_ID" 2>/dev/null | grep -q "$JOB_ID"; then
            echo "Error: Slurm job $JOB_ID is no longer in the queue. It may have failed during initialization."
            echo "Please check vllm_${JOB_ID}.log for details."
            exit 1
        fi
    fi
    sleep 5
done

# Source the generated environment variables
source "$ENDPOINT_FILE"

# Extract the IP address for tunneling instructions
COMPUTE_IP=$(echo $OPENAI_API_BASE | awk -F'[/:]' '{print $4}')

echo ""
echo "=========================================================="
echo "✅ Success! Decentralized LLM Proxy is running."
echo "=========================================================="
echo "For Cluster Workers (e.g., Lean4 Fleet):"
echo "  Before running your worker scripts, load the endpoint:"
echo "  source $ENDPOINT_FILE"
echo ""
echo "For Local Laptop Access (SSH Port Forwarding):"
echo "  Run this command on your laptop to tunnel to the compute node:"
echo "  ssh -L 4000:${COMPUTE_IP}:4000 your_username@grex.hpc.umanitoba.ca"
echo "=========================================================="
